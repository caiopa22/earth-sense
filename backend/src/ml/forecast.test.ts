import { describe, expect, it } from 'vitest';
import { forecastSensor, predictHumidity } from './forecast.ts';
import fixture from './parity.fixture.json' with { type: 'json' };

describe('TypeScript x Python parity (Ridge)', () => {
  it('uses 20 real samples generated by ml/train.py', () => {
    expect(fixture).toHaveLength(20);
  });

  it.each(fixture.map((row, i) => [i, row] as const))('sample %i', (_, row) => {
    const predicted = predictHumidity(row.window, row.sensor_index);
    expect(Math.abs(predicted - row.expected)).toBeLessThan(1e-6);
  });
});

describe('forecastSensor', () => {
  const at = (minutes: number) => new Date(Date.UTC(2026, 10, 11, 12, minutes)).toISOString();
  const nowAt = (minutes: number) => Date.parse(at(minutes));

  it('returns insufficient_data with fewer than 4 readings', () => {
    const result = forecastSensor(1, [
      { humidity_pct: 50, timestamp: at(0) },
      { humidity_pct: 51, timestamp: at(5) },
      { humidity_pct: 52, timestamp: at(10) },
    ], nowAt(12));
    expect(result.status).toBe('insufficient_data');
  });

  it('sorts by collection time and uses the 4 most recent', () => {
    const readings = [
      { humidity_pct: 53, timestamp: at(15) },
      { humidity_pct: 10, timestamp: at(-60) }, // old, outside the window
      { humidity_pct: 50, timestamp: at(0) },
      { humidity_pct: 52, timestamp: at(10) },
      { humidity_pct: 51, timestamp: at(5) },
    ];
    const result = forecastSensor(1, readings, nowAt(20));
    expect(result.status).toBe('ok');
    if (result.status !== 'ok') return;
    expect(result.predicted_humidity_pct).toBeCloseTo(predictHumidity([50, 51, 52, 53], 1), 2);
    expect(result.based_on).toBe(at(15));
    expect(result.forecast_for).toBe(at(45));
  });

  it('rejects windows with a gap larger than allowed', () => {
    const result = forecastSensor(1, [
      { humidity_pct: 50, timestamp: at(0) },
      { humidity_pct: 51, timestamp: at(5) },
      { humidity_pct: 52, timestamp: at(40) },
      { humidity_pct: 53, timestamp: at(45) },
    ], nowAt(46));
    expect(result.status).toBe('insufficient_data');
  });

  const window = [
    { humidity_pct: 50, timestamp: at(0) },
    { humidity_pct: 51, timestamp: at(5) },
    { humidity_pct: 52, timestamp: at(10) },
    { humidity_pct: 53, timestamp: at(15) },
  ];

  it('forecasts when the latest reading is exactly 15 min old', () => {
    expect(forecastSensor(1, window, nowAt(30)).status).toBe('ok');
  });

  it('returns stale_data when the latest reading is older than 15 min', () => {
    const result = forecastSensor(1, window, nowAt(31));
    expect(result.status).toBe('stale_data');
    if (result.status !== 'stale_data') return;
    expect(result.last_reading_at).toBe(at(15));
  });
});
